# ─── スタイル定義 ────────────────────────────────────────────
HEADER_FILL   = PatternFill("solid", fgColor="1F3864")   # 濃紺
SUBROW_FILL_A = PatternFill("solid", fgColor="DCE6F1")   # 薄青（奇数行）
SUBROW_FILL_B = PatternFill("solid", fgColor="FFFFFF")   # 白（偶数行）
PROBLEM_FILL  = PatternFill("solid", fgColor="FCE4D6")   # 薄オレンジ（問題点）
CURRENT_FILL  = PatternFill("solid", fgColor="FFF2CC")   # 薄黄（現行文）
IMPROVE_FILL  = PatternFill("solid", fgColor="E2EFDA")   # 薄緑（改善文）

HEADER_FONT   = Font(name="Meiryo UI", bold=True, color="FFFFFF", size=11)
BODY_FONT     = Font(name="Meiryo UI", size=10)
BOLD_FONT     = Font(name="Meiryo UI", bold=True, size=10)

thin  = Side(style="thin",   color="AAAAAA")
thick = Side(style="medium", color="444444")
THIN_BORDER  = Border(left=thin,  right=thin,  top=thin,  bottom=thin)
THICK_BORDER = Border(left=thick, right=thick, top=thick, bottom=thick)

WRAP = Alignment(wrap_text=True, vertical="top")
CENTER_WRAP = Alignment(wrap_text=True, vertical="center", horizontal="center")

# ─── 列幅設定 ────────────────────────────────────────────────
col_widths = {
    "A": 5,    # No
    "B": 22,   # 条文
    "C": 40,   # 問題点
    "D": 45,   # 現行文
    "E": 50,   # 改善文
}
for col, width in col_widths.items():
    ws.column_dimensions[col].width = width

# ─── ヘッダー行 ──────────────────────────────────────────────
headers = ["No", "条文・条番号", "問題点", "現行文（問題のある条文）", "改善文（修正案）"]
ws.row_dimensions[1].height = 30
for ci, h in enumerate(headers, start=1):
    cell = ws.cell(row=1, column=ci, value=h)
    cell.font      = HEADER_FONT
    cell.fill      = HEADER_FILL
    cell.alignment = CENTER_WRAP
    cell.border    = THICK_BORDER

# ─── データ行の書き込み ───────────────────────────────────────
ROW_HEIGHT = 18   # 基本行高さ

current_row = 2
for idx, r in enumerate(rows):
    fill_base = SUBROW_FILL_A if idx % 2 == 0 else SUBROW_FILL_B

    # 各セルの内容・スタイルをまとめる
    cells_def = [
        (r["no"],    BOLD_FONT, CENTER_WRAP, fill_base,    THIN_BORDER),
        (r["条文"],  BOLD_FONT, WRAP,        fill_base,    THIN_BORDER),
        (r["問題点"],BODY_FONT, WRAP,        PROBLEM_FILL, THIN_BORDER),
        (r["現行文"],BODY_FONT, WRAP,        CURRENT_FILL, THIN_BORDER),
        (r["改善文"],BODY_FONT, WRAP,        IMPROVE_FILL, THIN_BORDER),
    ]

    # 行高さ：最も長いセルの改行数に合わせて動的に設定
    max_lines = max(
        len(str(r["問題点"]).split("\n")),
        len(str(r["現行文"]).split("\n")),
        len(str(r["改善文"]).split("\n")),
    )
    ws.row_dimensions[current_row].height = max(ROW_HEIGHT * max_lines, 60)

    for ci, (val, fnt, align, fill, border) in enumerate(cells_def, start=1):
        cell = ws.cell(row=current_row, column=ci, value=str(val) if not isinstance(val, int) else val)
        cell.font      = fnt
        cell.alignment = align
        cell.fill      = fill
        cell.border    = border

    current_row += 1

# ─── 凡例行 ──────────────────────────────────────────────────
ws.row_dimensions[current_row].height = 16
legend_items = [
    ("C", PROBLEM_FILL, "問題点"),
    ("D", CURRENT_FILL, "現行文（問題のある条文）"),
    ("E", IMPROVE_FILL, "改善文（修正案）"),
]
for col_letter, fill, label in legend_items:
    col_idx = ord(col_letter) - ord("A") + 1
    cell = ws.cell(row=current_row, column=col_idx, value=f"■ {label}")
    cell.font      = Font(name="Meiryo UI", bold=True, size=9, color="444444")
    cell.fill      = fill
    cell.alignment = Alignment(horizontal="center", vertical="center")
    cell.border    = THIN_BORDER

# ─── ウィンドウ枠の固定（ヘッダー行） ───────────────────────
ws.freeze_panes = "A2"

# ─── 保存 ─────────────────────────────────────────────────
output_path = "/home/user/umb/就業規則_悪い点と改善案.xlsx"
wb.save(output_path)
print(f"Saved: {output_path}")
